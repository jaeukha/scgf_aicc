def run(name, turns):
    with httpx.Client(timeout=90) as c:
        sid = c.post(B, json={}).json()["session_id"]
        for sp, t in turns:
            r = c.post(f"{B}/{sid}/simulate", json={"text": t, "speaker": sp}).json()
    return r["routing"]

def endpoint(p):
    if p.get("destination"): return p["destination"]
    s = p["steps"][-1] if p["steps"] else None
    return "?" + s["title"] if s else "?"

sel = sys.argv[1:] if __name__ == "__main__" else ["none"]
out = []
ok = 0
for i, (name, turns, exp) in enumerate(CASES):
    if sel and str(i) not in sel: continue
    try:
        rt = run(name, turns)
    except Exception as e:
        print(i, name, "ERROR", e); continue
    got = {p["topic"]: endpoint(p) for p in rt.get("paths", [])}
    req = {k: v for k, v in exp.items() if v != "*"}
    allowed = set(exp)
    good = all(got.get(k) == v for k, v in req.items()) and set(got) <= allowed and bool(exp or not got)
    ok += good
    tops = {t["topic"]: f'{t["choice"]}{t["probability"]:.2f}{"" if t["certain"] else "?"}' for t in rt.get("topics", []) if t["choice"] != "해당 없음" or not t["certain"]}
    steps = [[(s["title"], s["choice"], round(s["probability"], 2), s["certain"]) for s in p["steps"]] for p in rt.get("paths", [])]
    line = f'{i:2} {"OK " if good else "BAD"} {name} | exp={exp} | got={got} | topics={tops} | steps={steps}'
    print(line, flush=True); out.append(line)
print(f"{ok}/{len(out)}")
